def max_val(m, n, val):
    # 每步最多前进3格，m步最多走3*m格，不够n格 → 无解
    if m * 3 < n:
        return -1
    # 跳跃次数 ≥ 格子数：每次跳1格，全部格子都能踩，总和就是答案
    if m >= n:
        return sum(val)
    
    # dp[m+1行][n列]，初始全部-1（不可达）
    dp = [[-1] * n for _ in range(m + 1)]
    
    # 初始化 i=1：只用1次跳跃，可以跳到0、1、2位置
    # 跳一次，最多前进3格：起点在-1，-1+1=0，-1+2=1，-1+3=2
    for j in range(3):
        dp[1][j] = val[j]
    
    # i 从2到m：枚举一共使用i次跳跃
    for i in range(2, m + 1):
        # j：当前落到位置j
        for j in range(n):
            maxv = -1
            # 上一跳，是从 j-1 / j-2 / j-3 跳过来（k=1,2,3）
            for k in range(1, 4):
                prev = j - k
                # prev >=0 位置合法，并且 i-1次跳跃可以到达prev
                if prev >= 0 and dp[i - 1][prev] != -1:
                    maxv = max(maxv, dp[i - 1][prev])
            # 找到合法的上一个状态，就更新dp[i][j]
            if maxv != -1:
                dp[i][j] = maxv + val[j]
                
    # 答案：恰好m跳，落到最后一格 n-1 的最大价值
    return dp[m][n - 1]
